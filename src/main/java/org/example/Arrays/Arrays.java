package org.example.Arrays;

public class Arrays {

    public static void main(String[] args) {


        int[] arr = {1, 23, 4, 5, 6};


        int count = arr.length;

        for (int i = 0; i < count; i++) {

            System.out.println(arr[i]);
        }
        System.out.println("total lenght" + count);
    }
}
